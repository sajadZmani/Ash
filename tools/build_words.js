#!/usr/bin/env node
/*
 * Builds data/words.js from words.txt.
 *
 *   node tools/build_words.js
 *
 * words.txt: "# name" starts a category, then one word per line as "word|level" (level 1, 2 or 3;
 * 2 when left out). Lines starting with // are comments.
 * A word seen before (in any category, ignoring spaces, half-spaces and Arabic letter forms) is
 * dropped, and so is any word with a part in tools/blocked_words.txt. Both are reported.
 */
'use strict';

var fs = require('fs');
var path = require('path');

var ROOT = path.join(__dirname, '..');
var SRC = path.join(ROOT, 'words.txt');
var BLOCK = path.join(__dirname, 'blocked_words.txt');
var OUT = path.join(ROOT, 'data', 'words.js');

// Persian letter forms, single spaces, half-space (ZWNJ) kept as typed.
function clean(s) {
  return s.replace(/ي/g, 'ی').replace(/ى/g, 'ی').replace(/ك/g, 'ک').replace(/ۀ/g, 'هٔ')
    .replace(/[\u064B-\u0652]/g, '') // harakat
    .replace(/\u200C+/g, '\u200C').replace(/\s+/g, ' ').trim();
}

// For comparing: no spaces or half-spaces.
function key(s) { return clean(s).replace(/[\s\u200C]/g, ''); }

function parts(s) { return clean(s).split(/[\s\u200C]+/); }

var blocked = {};
fs.readFileSync(BLOCK, 'utf8').split('\n').forEach(function (line) {
  if (/^\s*#/.test(line)) return;
  line.split(/\s+/).forEach(function (w) { if (w) blocked[clean(w)] = true; });
});

var cats = [], cat = null, seen = {}, problems = [];

fs.readFileSync(SRC, 'utf8').split('\n').forEach(function (raw, i) {
  var line = raw.trim(), at = 'words.txt:' + (i + 1);
  if (!line || line.indexOf('//') === 0) return;
  if (line[0] === '#') {
    cat = { name: clean(line.slice(1)), w: [[], [], []] };
    cats.push(cat);
    return;
  }
  if (!cat) { problems.push(at + ' word before any "# category" line: ' + line); return; }
  var bits = line.split('|');
  var word = clean(bits[0]);
  var level = bits.length > 1 ? parseInt(bits[1], 10) : 2;
  if (!word) return;
  if (!(level >= 1 && level <= 3)) { problems.push(at + ' level must be 1, 2 or 3: ' + line); level = 2; }
  var bad = parts(word).filter(function (p) { return blocked[p]; });
  if (bad.length) { problems.push(at + ' blocked (' + bad.join('، ') + '): ' + word); return; }
  var k = key(word);
  if (seen[k]) { problems.push(at + ' duplicate of "' + seen[k] + '": ' + word); return; }
  seen[k] = word + '» in «' + cat.name;
  cat.w[level - 1].push(word);
});

cats = cats.filter(function (c) { return c.w[0].length + c.w[1].length + c.w[2].length; });

var out = '/* Generated by tools/build_words.js from words.txt. Do not edit; edit words.txt. */\n' +
  'window.ASH_WORDS = [\n' +
  cats.map(function (c) { return '  ' + JSON.stringify({ name: c.name, w: c.w }); }).join(',\n') +
  '\n];\n';
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out);

var totals = [0, 0, 0];
cats.forEach(function (c) {
  c.w.forEach(function (list, l) { totals[l] += list.length; });
  console.log(c.name + ': ' + c.w.map(function (l) { return l.length; }).join(' / '));
});
var all = totals[0] + totals[1] + totals[2];
console.log('\n' + cats.length + ' categories, ' + all + ' words (easy ' + totals[0] + ', medium ' +
  totals[1] + ', hard ' + totals[2] + ') -> data/words.js');
if (problems.length) {
  console.log('\nDropped or fixed:');
  problems.forEach(function (p) { console.log('  ' + p); });
}
